import { test, expect } from '@playwright/test';
const token='browser-test-operator-token-32-bytes';
test('manual case executes and timeline survives offline reconnect and reload', async ({ page, context }) => {
  await page.goto('/');
  await page.getByLabel('Operator token').fill(token);await page.getByRole('button',{name:'Connect',exact:true}).click();
  await page.getByLabel('Title',{exact:true}).first().fill('Checkout timeout browser fixture');
  await page.getByLabel('Description').fill('<script>window.injected=true</script>');
  await page.getByRole('button',{name:'Create case',exact:true}).click();
  await expect(page.locator('#case-status')).toHaveText('awaiting review');
  await expect(page.locator('#timeline li')).toHaveCount(4);
  await expect(page.locator('#results')).toContainText('No service was inspected');
  await expect(page.locator('#case-description')).toHaveText('<script>window.injected=true</script>');
  expect(await page.evaluate(()=>('injected' in window))).toBe(false);
  const id=await page.locator('#case-id').textContent();
  await page.getByRole('link',{name:'Inspect persisted evidence'}).click();
  await expect(page.locator('#timeline pre')).toContainText('insufficient_evidence');
  const snapshot=await (await context.request.get(`/api/v1/cases/${id}`,{headers:{Authorization:`Bearer ${token}`}})).json();
  await expect(page.locator('#connection')).toHaveText('Timeline live');
  await context.setOffline(true);
  const renamed=await context.request.post(`/api/v1/cases/${id}/rename`,{headers:{Authorization:`Bearer ${token}`},data:{schema_version:1,idempotency_key:`offline-rename-${id}`,actor:'operator',reason:'Update while browser disconnected',title:'Updated while offline',expected_version:snapshot.case.version}});
  expect(renamed.ok()).toBe(true);
  await context.setOffline(false);
  await expect(page.locator('#case-title')).toHaveText('Updated while offline');
  await expect(page.locator('#timeline li')).toHaveCount(5);
  const ids=await page.locator('#timeline li').evaluateAll(nodes=>nodes.map(n=>(n as HTMLElement).dataset.eventId));
  expect(new Set(ids).size).toBe(5);
  await page.reload();await expect(page.locator('#timeline li')).toHaveCount(5);await expect(page.locator('#case-title')).toHaveText('Updated while offline');
  await page.getByText('Update title',{exact:true}).click();
  await page.locator('#rename-title').fill('Stale browser edit');
  await page.locator('#rename-reason').fill('Edit from an outdated view');
  await page.route(`**/api/v1/cases/${id}/rename`,async route=>{
    const sent=route.request().postDataJSON();
    const winner=await context.request.post(`/api/v1/cases/${id}/rename`,{headers:{Authorization:`Bearer ${token}`},data:{...sent,idempotency_key:`competing-${id}`,title:'Concurrent operator update'}});
    expect(winner.ok()).toBe(true);await route.continue();
  });
  await page.getByRole('button',{name:'Save with version check'}).click();
  await expect(page.locator('#error')).toContainText('reload before retrying');
  await expect(page.locator('#case-title')).toHaveText('Concurrent operator update');
  await expect(page.locator('#timeline li')).toHaveCount(6);
  await page.getByText('Update title',{exact:true}).click();
  await page.screenshot({path:'test-results/watchhouse-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});await page.screenshot({path:'test-results/watchhouse-mobile.png',fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});
